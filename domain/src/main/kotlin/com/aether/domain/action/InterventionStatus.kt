package com.aether.domain.action

/**
 * Distinguishes user-initiated commands from proactive assistant nudges.
 */
enum class InterventionCategory {
    /**
     * Explicit user command (e.g. "Remind me at 10 PM", "Set alarm for 7 AM").
     * Bypasses daily proactive interruption budget, thread cooldowns, and quiet hours.
     */
    SOLICITED,

    /**
     * Autonomous proactive nudge from Aether based on friction detection.
     * Strictly bounded by daily circadian budget, 10-hour inter-intervention cooldown,
     * thread cooldowns, and quiet hours.
     */
    PROACTIVE_INTERVENTION,
}

/**
 * Technical delivery status of an intervention at the Android OS surface.
 */
enum class InterventionStatus {
    /** Candidate generated by domain reasoning; not yet evaluated by restraint policy. */
    PROPOSED,

    /**
     * Successfully accepted by Android NotificationManager and drawn in notification shade.
     * Consumes daily proactive budget irrevocably. 10-hour cooldown starts immediately.
     */
    POSTED,

    /** Suppressed by restraint policy or quiet hours before reaching notification shade. */
    SUPPRESSED,

    /** Notification was superseded, updated, or withdrawn before user interaction. */
    CANCELLED,

    /** User tapped 1-tap accept button or replied inline. */
    ACCEPTED,

    /** User swiped away, clicked dismiss, or gave negative feedback. */
    DISMISSED,

    /** Technical delivery failed (e.g. notification channel blocked or security exception). */
    FAILED,
}
